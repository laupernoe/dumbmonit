def main():
    data = json.loads((HERE / "data" / "devices.json").read_text())
    svgs = json.loads((HERE / "svgs.json").read_text())
    templates = {p.stem: p.read_text() for p in (HERE / "templates").glob("*.html")}
    counts = {"@@NDEV@@": len(data["devices"]), "@@NFAM@@": len(data["families"]), "@@NCHANNELS@@": len(data["channels"])}
    base, strings = load_strings(counts)
    check_shapes(base, strings)
    for f in data["families"]:
        for k in (f"fam_{f['id']}_name", f"fam_{f['id']}_blurb"):
            assert k in base, f"missing string {k}"
    pages = build_pages(data)
    files = {}
    for page in pages:
        for code, *_ in LANGS:
            d = abs_dir(code, page["path"])
            path = OUT / d / "index.html" if d else OUT / "index.html"
            files[path] = build_page(templates, svgs, strings, data, page, code)
    files[OUT / "sitemap.xml"] = build_sitemap(pages)
    files[OUT / "404.html"] = NOT_FOUND
    if "--check" in sys.argv:
        stale = [str(p) for p, c in files.items() if not p.exists() or p.read_text() != c]
        if stale:
            raise SystemExit("out of date, run site-src/build.py: " + ", ".join(stale[:10]))
        return
    for p, c in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(c)
    for c, *_ in LANGS:
        f = HERE / "strings" / f"{c}.json"
        if c != "en" and f.exists():
            miss = sorted(set(base) - set(json.loads(f.read_text())))
            if miss:
                print(f"{c}: {len(miss)} keys fall back to English")
    print("built", len(pages), "pages x", len(LANGS), "languages")


if __name__ == "__main__":
    main()
