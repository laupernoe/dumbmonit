def lang_dir(code):
    return "" if code == "en" else code


def abs_dir(code, path):
    return posixpath.join(lang_dir(code), path).strip("/")


def rel(code, path, to_code, to_path):
    """Relative URL from the page (code, path) to the page (to_code, to_path)."""
    cur = "/" + abs_dir(code, path)
    dst = "/" + abs_dir(to_code, to_path)
    r = posixpath.relpath(dst, cur)
    return "./" if r == "." else r + "/"


def page_url(code, path):
    d = abs_dir(code, path)
    return SITE + (d + "/" if d else "")


def root_of(code, path):
    r = posixpath.relpath("/", "/" + abs_dir(code, path))
    return "" if r == "." else r + "/"


