def render_steps(steps):
    out = []
    for s in steps:
        head, _, code = s.partition("\n")
        li = f"<li><p>{esc(head)}</p>"
        if code.strip():
            li += f"<pre><code>{esc(code.strip())}</code></pre>"
        out.append(li + "</li>")
    return "<ol class=\"setup-steps\">" + "".join(out) + "</ol>"


def render_device(ctx, dev):
    t = ctx["t"]
    parts = [f'<article class="dev" id="{dev["kind"]}">']
    parts.append(f'<header><h2>{esc(dev["label"])}</h2><span class="label-tape">{esc(dev["kind"])}</span></header>')
    parts.append(f'<p class="summary">{esc(dev["summary"])}</p>')
    if dev["examples"]:
        chips = "".join(f"<li>{esc(e)}</li>" for e in dev["examples"])
        parts.append(f'<p class="label-tape" style="margin-top:14px">{esc(t["fp_examples"])}</p><ul class="chips" style="margin-top:6px">{chips}</ul>')
    parts.append('<div class="dev-grid">')

    # what you need
    needs = [c for c in dev["credentials"] if c["kind"] != "none"]
    body = "<section><h3>" + esc(t["fp_needs"]) + "</h3>"
    if needs:
        body += "<ul class=\"needs\">" + "".join(
            f"<li><strong>{esc(c['label'])}</strong>" + (f"<span>{esc(c['help'])}</span>" if c["help"] else "") + "</li>"
            for c in needs
        ) + "</ul>"
        if any(c["kind"] == "none" for c in dev["credentials"]):
            body += f'<p class="muted">{esc(t["fp_nocred"])}</p>'
    else:
        body += f'<p class="muted">{esc(t["fp_nocred"])}</p>'
    if dev["default_port"]:
        body += f'<p class="muted">{esc(t["fp_port"])}: <code>{dev["default_port"]}</code></p>'
    body += "</section>"
    parts.append(body)

    # rules
    rules = dev["rules"]

    def rule_li(r):
        key, cls = SEVERITY.get(r["severity"], ("sev_info", "plate-info"))
        desc = f"<span>{esc(r['description'])}</span>" if r["description"] else ""
        return f'<li><span class="plate {cls}">{esc(t[key])}</span><strong>{esc(r["name"])}</strong>{desc}</li>'

    r_html = f'<section><h3>{esc(t["fp_rules"])} <span class="label-tape">{len(rules)}</span></h3><ul class="rules">'
    r_html += "".join(rule_li(r) for r in rules[:RULES_SHOWN]) + "</ul>"
    if len(rules) > RULES_SHOWN:
        more = esc(t["fp_more"].replace("{n}", str(len(rules) - RULES_SHOWN)))
        r_html += f'<details class="more-rules"><summary>{more}</summary><ul class="rules">' + "".join(rule_li(r) for r in rules[RULES_SHOWN:]) + "</ul></details>"
    r_html += "</section>"
    parts.append(r_html)
    parts.append("</div>")

    setup = dev["setup"]
    if setup["steps"]:
        parts.append(
            f'<details class="setup"><summary>{esc(t["fp_setup"])}: {esc(setup["title"])}</summary>'
            + render_steps(setup["steps"])
            + (f'<p class="warn"><strong>{esc(t["fp_warn"])}.</strong> {esc(setup["warning"])}</p>' if setup["warning"] else "")
            + "</details>"
        )
    parts.append(
        f'<p class="dev-doc"><a class="btn btn-secondary btn-sm" href="{esc(doc_url(ctx["docs"], dev))}">{esc(t["fp_doc"])}</a></p>'
    )
    parts.append("</article>")
    return "\n".join(parts)


# Screenshots of the live demo (site-src/static/assets/shots): desktop at 1440 x 900 CSS px, captured at 2x
# (2880 x 1800, plus a 1440 wide copy), phone at 390 x 844 at 2x (780 x 1688). Each in light and
# dark, AVIF with a WebP fallback; the reader's prefers-color-scheme picks the light.
SHOT_D = (2880, 1800)
SHOT_M = (780, 1688)


def shot(root, name, alt_key, mode):
    """<picture> for one screenshot. mode: 'hero' (eager, phone image under 600 px),
    'both' (lazy, phone image under 600 px), 'wide' (lazy, desktop image everywhere)."""
    base = f"{root}assets/shots/{name}"
    sizes = "(min-width: 1180px) 1100px, 100vw" if mode == "hero" else "(min-width: 980px) 640px, 100vw"
    out = ["<picture>"]
    for scheme, media in (("dark", "(prefers-color-scheme: dark)"), ("light", None)):
        if mode in ("hero", "both"):
            m = "(max-width: 599px)" + (f" and {media}" if media else "")
            for ext in ("avif", "webp"):
                out.append(f'<source type="image/{ext}" media="{m}" srcset="{base}-phone-{scheme}.{ext}" width="{SHOT_M[0]}" height="{SHOT_M[1]}">')
        for ext in ("avif", "webp"):
            if scheme == "light" and ext == "webp":
                break
            mq = f' media="{media}"' if media else ""
            out.append(
                f'<source type="image/{ext}"{mq} srcset="{base}-{scheme}-1x.{ext} 1440w, {base}-{scheme}.{ext} 2880w" '
                f'sizes="{sizes}" width="{SHOT_D[0]}" height="{SHOT_D[1]}">'
            )
    load = 'fetchpriority="high"' if mode == "hero" else 'loading="lazy" decoding="async"'
    out.append(
        f'<img src="{base}-light-1x.webp" srcset="{base}-light-1x.webp 1440w, {base}-light.webp 2880w" sizes="{sizes}" '
        f'alt="{{{{{alt_key}}}}}" width="{SHOT_D[0]}" height="{SHOT_D[1]}" {load}>'
    )
    out.append("</picture>")
    return "\n".join(out)


# Roadmap status: label key, plate colour class, icon (the text and the icon say it, not the colour alone).
RM_STATUS = {
    "planned": ("rm_planned", "plate-info", '<circle cx="12" cy="12" r="8"/>'),
    "progress": ("rm_progress", "plate-advisory", '<circle cx="12" cy="12" r="8"/><path d="M12 4a8 8 0 0 1 0 16Z" fill="currentColor"/>'),
    "idea": ("rm_idea", "plate-info", '<circle cx="12" cy="12" r="8" stroke-dasharray="3 3.2"/>'),
    "delivered": ("rm_delivered", "plate-signal", '<path d="m5 12.5 4.5 4.5L19 7.5"/>'),
}


def render_roadmap(ctx, roadmap):
    """The roadmap page body: one block per section of site-src/data/roadmap.json."""
    t, code = ctx["t"], ctx["code"]
    pick = lambda m: m.get(code) or m["en"]
    out = []
    plate_of = lambda st: (
        f'<span class="plate {RM_STATUS[st][1]}"><svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.4" '
        f'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{RM_STATUS[st][2]}</svg>{esc(t[RM_STATUS[st][0]])}</span>'
    )
    for sec in roadmap["sections"]:
        sid = esc(sec["id"])
        head = f'<h2 id="{sid}-h">{esc(pick(sec["title"]))}</h2>'
        if sec.get("label"):
            head = f'<p class="label-tape">{esc(pick(sec["label"]))}</p>' + head
        if "groups" in sec:
            # Idea sections are long: one collapsible <details> per category (closed by default).
            groups = []
            for g in sec["groups"]:
                lis = "\n".join(
                    f'\t\t\t\t<li>{esc(it["name"] if "name" in it else pick(it["text"]))}</li>' for it in g["items"]
                )
                groups.append(
                    f'\t\t<details class="rm-group"><summary><span class="rm-gtitle">{esc(pick(g["title"]))}</span>'
                    f'<span class="rm-count tnum">{len(g["items"])} {esc(t["rm_count"])}</span>{plate_of(g["items"][0]["status"])}</summary>\n'
                    f'\t\t\t<ul class="rm-chips">\n{lis}\n\t\t\t</ul>\n\t\t</details>'
                )
            out.append(
                f'\t<section class="rm-sec" id="{sid}" aria-labelledby="{sid}-h">\n'
                f'\t\t<div class="rm-head">{head}</div>\n' + "\n".join(groups) + "\n\t</section>"
            )
            continue
        items = []
        for it in sec["items"]:
            ver = f'<strong class="rm-ver tnum">{esc(it["version"])}</strong> ' if it.get("version") else ""
            items.append(f'\t\t\t<li>{plate_of(it["status"])}<span class="rm-text">{ver}{esc(pick(it["text"]))}</span></li>')
        out.append(
            f'\t<section class="rm-sec" id="{sid}" aria-labelledby="{sid}-h">\n'
            f'\t\t<div class="rm-head">{head}</div>\n'
            f'\t\t<ul class="rm-list">\n' + "\n".join(items) + "\n\t\t</ul>\n\t</section>"
        )
    return "\n".join(out)


def fragments(ctx, page, data):
    """The @@NAME@@ blocks a page template may contain."""
    t, link = ctx["t"], ctx["link"]
    devs = data["devices"]
    counts = {f["id"]: len(f["kinds"]) for f in data["families"]}
    frag = {
        "FAMILY_CARDS": "\n".join(family_card(ctx, f, counts[f["id"]]) for f in data["families"]),
        "CHANNEL_CHIPS": "\n".join(f"\t\t\t<li>{esc(c['label'])}</li>" for c in data["channels"]),
        "FAMILY_CHIPS": "\n".join(
            f'\t\t\t\t\t<li><a href="{link("devices/" + f["id"] + "/")}" data-family="{f["id"]}">{esc(fam_name(t, f["id"]))}</a></li>'
            for f in data["families"]
        ),
        "CATALOG": "\n".join(device_card(ctx, d) for d in devs),
        "N_DEV": str(len(devs)),
        "N_CH": str(len(data["channels"])),
    }
    for name, value in DIAGRAMS.items():
        frag[f"DIAGRAM:{name}"] = value
    if page["tmpl"] == "roadmap":
        frag["ROADMAP"] = render_roadmap(ctx, data["roadmap"])
    if page["tmpl"] == "family":
        fid = page["family"]
        mine = [d for d in devs if d["family"] == fid]
        frag["FAMILY_NAME"] = esc(fam_name(t, fid))
        frag["FAMILY_BLURB"] = esc(t[f"fam_{fid}_blurb"])
        frag["FAMILY_TOC"] = "\n".join(f'\t\t\t<li><a href="#{d["kind"]}">{esc(d["label"])}</a></li>' for d in mine)
        frag["FAMILY_DEVICES"] = "\n".join(render_device(ctx, d) for d in mine)
        frag["OTHER_FAMILIES"] = "\n".join(
            f'\t\t\t<li><a href="{link("devices/" + f["id"] + "/")}">{esc(fam_name(t, f["id"]))}</a></li>'
            for f in data["families"] if f["id"] != fid
        )
    return frag


