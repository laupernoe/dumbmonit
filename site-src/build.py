#!/usr/bin/env python3
"""Builds the product website: several pages, nine languages, from templates and string files.

    python3 site-src/extract.py          # refresh site-src/data/devices.json from the project sources
    python3 site-src/build.py            # writes website/**/index.html, 404.html, sitemap.xml
    python3 site-src/build.py --check    # builds in memory and fails if website/ is out of date

Source of truth:
  site-src/templates/base.html     header (navigation, language selector), footer, <head>: shared by every page
  site-src/templates/<page>.html   the body of each kind of page; every text is a {{key}} placeholder
  site-src/strings/<lang>.json     the texts (en is the base; a missing key falls back to English)
  site-src/svgs.json               inline icons, referenced as [[svgN]] inside texts
  site-src/data/devices.json       the device catalogue (generated by extract.py, never edited by hand)

Pages: home, features, devices (catalogue), one page per device family, install, community.
English lives at the site root (the historical URL), the other languages in /<code>/.
The locale list is the one of web/messages/ and of mkdocs.yml (docs).
"""
import html
import json
import posixpath
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "website"

SITE = "https://dumbmonit.app/"
# Where the documentation lives. One constant: change it here if the layout moves.
# One Read the Docs project per language: <DOCS_HOST><rtd code>/latest/.
DOCS_HOST = "https://dumbmonit.readthedocs.io/"
LASTMOD = "2026-10-15"

# code, name in its own language, short label, Open Graph locale, Read the Docs language
LANGS = [
    ("en", "English", "EN", "en_US", "en"),
    ("fr", "Français", "FR", "fr_FR", "fr"),
    ("de", "Deutsch", "DE", "de_DE", "de"),
    ("es", "Español", "ES", "es_ES", "es"),
    ("it", "Italiano", "IT", "it_IT", "it"),
    ("pt", "Português", "PT", "pt_PT", "pt"),
    ("pt-BR", "Português (Brasil)", "PT-BR", "pt_BR", "pt-br"),
    ("ru", "Русский", "RU", "ru_RU", "ru"),
    ("zh-Hans", "简体中文", "中文", "zh_CN", "zh-cn"),
]

GLOBE = (
    '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" '
    'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><circle cx="12" cy="12" r="9"/>'
    '<path d="M3 12h18M12 3c2.6 2.7 3.9 5.7 3.9 9s-1.3 6.3-3.9 9c-2.6-2.7-3.9-5.7-3.9-9S9.4 5.7 12 3Z"/></svg>'
)

# Keyed by the word the docs and the UI use ("Warning" is the API'"'"'s critical, "Advisory" its warning).
SEVERITY = {"warning": ("sev_warning", "plate-warning"), "advisory": ("sev_advisory", "plate-advisory"), "info": ("sev_info", "plate-info")}
# Rules listed in full up to this many, the rest behind a "show more".
RULES_SHOWN = 6

KEY = r"[A-Za-z_][A-Za-z0-9_]*"


def esc(s):
    return html.escape(s, quote=True)


# ---------------------------------------------------------------------------
# strings

def load_strings(counts):
    base = json.loads((HERE / "strings" / "en.json").read_text())
    out = {}
    for code, *_ in LANGS:
        f = HERE / "strings" / f"{code}.json"
        tr = json.loads(f.read_text()) if f.exists() else {}
        unknown = set(tr) - set(base)
        if unknown:
            raise SystemExit(f"{code}: unknown keys {sorted(unknown)}")
        table = {**base, **tr}
        for k, v in table.items():
            for token, value in counts.items():
                v = v.replace(token, str(value))
            table[k] = v
        out[code] = table
    return base, out


def shape(text):
    """What a translation must keep from the source: tags, icon tokens, doc links and counters."""
    return sorted(re.findall(r"</?[a-z]+|\[\[svg\d+\]\]|@@DOCS@@[^\"]*|@@(?!DOCS)[A-Z]+@@|\{n\}", text))


def check_shapes(base, strings):
    errors = []
    for code, table in strings.items():
        for k, v in table.items():
            if code != "en" and shape(v) != shape(strings["en"][k]):
                errors.append(f"{code} {k}: markup differs from English")
    if errors:
        raise SystemExit("\n".join(errors))


