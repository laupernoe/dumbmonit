def build_sitemap(pages):
    rows = []
    for page in pages:
        for c, *_ in LANGS:
            links = "".join(
                f'\n    <xhtml:link rel="alternate" hreflang="{o}" href="{page_url(o, page["path"])}"/>' for o, *_ in LANGS
            ) + f'\n    <xhtml:link rel="alternate" hreflang="x-default" href="{page_url("en", page["path"])}"/>'
            rows.append(f"  <url>\n    <loc>{page_url(c, page['path'])}</loc>\n    <lastmod>{LASTMOD}</lastmod>{links}\n  </url>")
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n'
        + "\n".join(rows) + "\n</urlset>\n"
    )


