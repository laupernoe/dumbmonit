def detect_script(code, path):
    codes = {c.lower(): c for c, *_ in LANGS}
    return (
        "<script>\n(function () {\n"
        "\ttry {\n"
        "\t\tif (localStorage.getItem('dm-lang')) return;\n"
        "\t\tvar known = " + json.dumps(codes) + ";\n"
        "\t\tvar prefs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language];\n"
        "\t\tfor (var i = 0; i < prefs.length; i++) {\n"
        "\t\t\tvar l = String(prefs[i] || '').toLowerCase();\n"
        "\t\t\tvar code = known[l] || (l.indexOf('zh') === 0 ? 'zh-Hans' : known[l.split('-')[0]]);\n"
        "\t\t\tif (!code) continue;\n"
        "\t\t\tif (code !== 'en') location.replace('" + root_of("en", path) + "' + code + '/" + path + "' + location.hash);\n"
        "\t\t\treturn;\n"
        "\t\t}\n"
        "\t} catch (e) {}\n"
        "})();\n</script>"
    )


def build_page(templates, svgs, strings, data, page, code):
    t = strings[code]
    _, _name, _short, og, docs_dir = next(l for l in LANGS if l[0] == code)
    path = page["path"]
    link = lambda target: _link(code, path, target)
    ctx = {"t": t, "link": link, "docs": docs_dir}

    if page["tmpl"] == "family":
        fname = fam_name(t, page["family"])
        title = t["t_family"].replace("@@FAMILY@@", fname)
        desc = t[f"fam_{page['family']}_blurb"]
    else:
        title, desc = t[page["title"]], t[page["desc"]]

    body = templates[page["tmpl"]]
    frag = fragments(ctx, page, data)
    for name, value in frag.items():
        body = body.replace(f"@@{name}@@", value)

    nav_items = [
        ("features/", t["nav_features"]),
        ("devices/", t["nav_devices"]),
        ("install/", t["nav_install"]),
        ("community/", t["nav_community"]),
    ]
    nav = "\n".join(
        f'\t\t\t<a href="{link(p)}"' + (' aria-current="page"' if page["nav"] == p else "") + f">{esc(label)}</a>"
        for p, label in nav_items
    )
    items = []
    for c, n, _s, _o, _d in LANGS:
        cur = ' aria-current="true"' if c == code else ""
        items.append(f'\t\t\t\t<li><a href="{rel(code, path, c, path)}" hreflang="{c}" lang="{c}"{cur}>{n}</a></li>')
    short = next(l[2] for l in LANGS if l[0] == code)
    switcher = (
        '\t\t\t<details class="lang">\n'
        f'\t\t\t\t<summary aria-label="{esc(t["k187"])}">{GLOBE}<span>{short}</span></summary>\n'
        '\t\t\t\t<ul>\n' + "\n".join(items) + "\n\t\t\t\t</ul>\n\t\t\t</details>"
    )
    alternates = "\n".join(
        f'<link rel="alternate" hreflang="{c}" href="{page_url(c, path)}">' for c, *_ in LANGS
    ) + f'\n<link rel="alternate" hreflang="x-default" href="{page_url("en", path)}">'
    url = page_url(code, path)
    if page["tmpl"] == "home":
        jsonld = json.dumps({
            "@context": "https://schema.org", "@type": "SoftwareApplication", "name": "DumbMonit",
            "applicationCategory": "DeveloperApplication", "operatingSystem": "Linux (Docker), amd64",
            "license": "https://www.apache.org/licenses/LICENSE-2.0", "url": url, "inLanguage": code,
            "codeRepository": "https://github.com/laupernoe/dumbmonit",
            "offers": {"@type": "Offer", "price": "0", "priceCurrency": "USD"},
        }, separators=(",", ":"))
    else:
        jsonld = json.dumps({
            "@context": "https://schema.org", "@type": "WebPage", "name": title, "url": url, "inLanguage": code,
            "isPartOf": {"@type": "WebSite", "name": "DumbMonit", "url": SITE},
        }, ensure_ascii=False, separators=(",", ":"))

    script = DEVICES_SCRIPT if page["tmpl"] == "devices" else ""

    t_full = templates["base"].replace("@@BODY@@", body)
    for name, value in {
        "TITLE": esc(title), "DESC": esc(desc), "URL": url, "LANG": code, "OGLOCALE": og,
        "ALTERNATES": alternates, "NAV": nav, "SWITCHER": switcher, "ROOT": root_of(code, path),
        "JSONLD": jsonld, "SCRIPT": script,
        "DETECT": detect_script(code, path) if code == "en" else "",
    }.items():
        t_full = t_full.replace(f"@@{name}@@", value)

    # texts: attribute values escaped, then the rest
    t_full = re.sub(r'(="\s*)\{\{(' + KEY + r')\}\}"', lambda m: '="' + t[m.group(2)].replace('"', "&quot;") + '"', t_full)
    t_full = re.sub(r"\{\{(" + KEY + r")\}\}", lambda m: t[m.group(1)], t_full)
    t_full = re.sub(r"\[\[(svg\d+)\]\]", lambda m: svgs[m.group(1)], t_full)
    t_full = t_full.replace("@@DOCS@@", DOCS_HOST + docs_dir + "/latest/")
    t_full = re.sub(r"@@LINK:([^@]*)@@", lambda m: link(m.group(1)), t_full)
    t_full = t_full.replace('<script>\n\n</script>', "")
    leftover = re.search(r"@@[A-Za-z:_]+@@|\{\{[^}]*\}\}", t_full)
    assert not leftover, f"unfilled placeholder {leftover.group(0)} in {code}/{path}"
    return t_full


def _link(code, path, target):
    """Internal link: 'features/', 'devices/network/#snmp', '' (home)."""
    p, _, frag = target.partition("#")
    r = rel(code, path, code, p)
    if frag:
        r = ("" if r == "./" and p == path else r) + "#" + frag
    return r


