<#
.SYNOPSIS
    Deploys the DumbMonit agent to the servers of an Active Directory domain
    with one group policy.

.DESCRIPTION
    Easiest way to run it: open PowerShell as a domain administrator, go to the folder
    holding this file, and paste this single line (it removes the "security warning" of a
    downloaded file and the execution policy for this run only):

        Unblock-File .\Deploy-DumbMonit.ps1; powershell -NoProfile -ExecutionPolicy Bypass -File .\Deploy-DumbMonit.ps1

    Without targeting parameters, in an interactive console, the script asks what to cover
    (all Windows Servers of the domain, one OU, or one security group), shows the plan and
    asks for one confirmation. Pass -Yes to skip the questions, or any targeting parameter
    (-AllServers, -TargetOU, -SecurityGroup) for unattended use.

    Generated by DumbMonit (Add monitor > Server with the agent > Deploy with Active Directory)
    for the domain __DM_DOMAIN__. Run it once, as a domain administrator, on a
    domain controller or on a machine with the Group Policy Management and
    Active Directory PowerShell tools (RSAT).

    It is idempotent: running it again updates the group policy in place.

    By default, once the policy is deployed the script refreshes every targeted server right
    away (WinRM, or Invoke-GPUpdate as a fallback), so nobody waits for the 90-minute policy
    refresh, then watches the agent appear for up to 3 minutes. See -NoRefresh and -NoVerify.

    What it does:
      1. copies a small installation kit to SYSVOL (\\<domain>\SYSVOL\<domain>\DumbMonit),
         readable only by domain computers (or by -SecurityGroup) and administrators;
      2. creates or updates the group policy "DumbMonit Agent": an immediate
         scheduled task, run as SYSTEM at every policy refresh, that installs the
         agent when it is missing or out of date and does nothing otherwise;
      3. links the group policy to -TargetOU (and to Domain Controllers with
         -IncludeDomainControllers), optionally filtered on -SecurityGroup.

    Each server then enrolls itself under its fully qualified name with the
    fleet enrollment token embedded in this script, and receives its own
    identity. Keep this file like a password, and delete it once deployed.

.PARAMETER TargetOU
    Distinguished name of the organisational unit holding the servers, e.g.
    "OU=Servers,DC=corp,DC=example,DC=com". A parent OU covers its children. Omitted
    and non-interactive: the only OU that holds server computers is used; when there
    are several, the script stops and lists them. Servers in the CN=Computers
    container (not an OU) are only covered by -AllServers.

.PARAMETER IncludeDomainControllers
    Also link the group policy to the Domain Controllers OU.

.PARAMETER AllServers
    Link the group policy to the whole domain and restrict it, with a WMI filter, to
    machines running Windows Server (domain controllers included). Every server that
    joins the domain later gets the agent too, with nothing to maintain: no OU to pick,
    no security group to fill. Workstations are left alone. Not combinable with
    -SecurityGroup.

.PARAMETER SecurityGroup
    Only computers in this security group apply the group policy.

.PARAMETER Yes
    Do not ask anything: use the parameters as given (and the defaults of this kit),
    which includes refreshing all the servers now.

.PARAMETER NoRefresh
    Do not refresh the servers after deploying: they pick the policy up at their next
    refresh (within 90 minutes). Skips the verification too. Meant for automation.

.PARAMETER NoVerify
    Refresh the servers, but do not wait (up to 3 minutes) to see the agent appear on them.

.PARAMETER UseSysvol
    Also copy the agent binary to SYSVOL, for servers that cannot reach the
    DumbMonit server over HTTP(S) to download it. They still need to reach it
    to send their measurements.

.PARAMETER Remove
    Deletes the group policy, its links and the SYSVOL kit. Installed agents
    keep running; see -UninstallAgents.

.PARAMETER UninstallAgents
    Switches the group policy to uninstalling the agent from the servers it
    applies to. Run -Remove once they have refreshed their policies.

.EXAMPLE
    Unblock-File .\Deploy-DumbMonit.ps1; powershell -NoProfile -ExecutionPolicy Bypass -File .\Deploy-DumbMonit.ps1
    Recommended: one line to paste. The script then asks what to cover.

.EXAMPLE
    .\Deploy-DumbMonit.ps1 -WhatIf
    Shows what would be done, changes nothing.

.EXAMPLE
    .\Deploy-DumbMonit.ps1 -AllServers -Yes
    Every Windows Server of the domain, present and future, without any question.

.EXAMPLE
    .\Deploy-DumbMonit.ps1 -AllServers -Yes -NoRefresh
    Deploys the policy only; servers pick it up within 90 minutes (automation).

.EXAMPLE
    .\Deploy-DumbMonit.ps1 -AllServers -Yes -NoVerify
    Deploys and refreshes all servers now, without waiting to see the agents arrive.

.EXAMPLE
    .\Deploy-DumbMonit.ps1 -SecurityGroup "DumbMonit Servers"

.EXAMPLE
    .\Deploy-DumbMonit.ps1 -TargetOU "OU=Servers,DC=corp,DC=example,DC=com" -IncludeDomainControllers

.EXAMPLE
    .\Deploy-DumbMonit.ps1 -Remove
#>
