<#
.SYNOPSIS
    Deploys the DumbMonit agent to the servers of an Active Directory domain
    with one group policy.

.DESCRIPTION
    Generated by DumbMonit (Settings > Agents > Deploy with Active Directory)
    for the domain __DM_DOMAIN__. Run it once, as a domain administrator, on a
    domain controller or on a machine with the Group Policy Management and
    Active Directory PowerShell tools (RSAT).

    It is idempotent: running it again updates the group policy in place.

    What it does:
      1. copies a small installation kit to SYSVOL (\\<domain>\SYSVOL\<domain>\DumbMonit),
         readable only by domain computers (or by -SecurityGroup) and administrators;
      2. creates or updates the group policy "DumbMonit Agent": an immediate
         scheduled task, run as SYSTEM at every policy refresh, that installs the
         agent when it is missing or out of date and does nothing otherwise;
      3. links the group policy to -TargetOU (and to Domain Controllers with
         -IncludeDomainControllers), optionally filtered on -SecurityGroup.

    Each server then enrolls itself under its fully qualified name with the
    fleet enrollment token embedded in this script, and receives its own
    identity. Keep this file like a password, and delete it once deployed.

.PARAMETER TargetOU
    Distinguished name of the organisational unit holding the servers, e.g.
    "OU=Servers,DC=corp,DC=example,DC=com". Omitted: the only OU that holds
    server computers is used; when there are several, they are listed.

.PARAMETER IncludeDomainControllers
    Also link the group policy to the Domain Controllers OU.

.PARAMETER SecurityGroup
    Only computers in this security group apply the group policy.

.PARAMETER UseSysvol
    Also copy the agent binary to SYSVOL, for servers that cannot reach the
    DumbMonit server over HTTP(S) to download it. They still need to reach it
    to send their measurements.

.PARAMETER Remove
    Deletes the group policy, its links and the SYSVOL kit. Installed agents
    keep running; see -UninstallAgents.

.PARAMETER UninstallAgents
    Switches the group policy to uninstalling the agent from the servers it
    applies to. Run -Remove once they have refreshed their policies.

.EXAMPLE
    .\Deploy-DumbMonit.ps1 -WhatIf
    Shows what would be done, changes nothing.

.EXAMPLE
    .\Deploy-DumbMonit.ps1 -TargetOU "OU=Servers,DC=corp,DC=example,DC=com" -IncludeDomainControllers

.EXAMPLE
    .\Deploy-DumbMonit.ps1 -Remove
#>
[CmdletBinding(SupportsShouldProcess = $true, ConfirmImpact = 'Medium')]
param(
    [string]$TargetOU = [System.Text.Encoding]::UTF8.GetString([Convert]::FromBase64String('__DM_TARGET_OU_B64__')),
    [switch]$IncludeDomainControllers = [bool]::Parse('__DM_INCLUDE_DCS__'),
    [string]$SecurityGroup = [System.Text.Encoding]::UTF8.GetString([Convert]::FromBase64String('__DM_SECURITY_GROUP_B64__')),
    [switch]$UseSysvol = [bool]::Parse('__DM_SYSVOL__'),
    [string]$GpoName = 'DumbMonit Agent',
    [switch]$Remove,
    [switch]$UninstallAgents
)

$ErrorActionPreference = 'Stop'

# Valeurs posées par le serveur DumbMonit à la génération du kit.
$Domain         = '__DM_DOMAIN__'
$Url            = '__DM_URL__'
$ExpectedSha256 = '__DM_SHA256__'
$TokenHint      = '__DM_TOKEN_PREFIX__'
$Generated      = '__DM_GENERATED__'
# Installateur de l'agent et script exécuté par la tâche planifiée, tels que
# le serveur les livre ; le second porte le jeton de flotte.
$InstallerB64   = '__DM_INSTALLER_B64__'
$BootstrapB64   = '__DM_BOOTSTRAP_B64__'

$BinaryName   = 'dumbmonit-agent-windows-x86_64.exe'
$TaskName     = 'DumbMonit Agent'
# Extensions côté client des préférences « Tâches planifiées » : sans elles
# dans gPCMachineExtensionNames, les serveurs ignorent le fichier XML.
$ExtensionNames = '[{00000000-0000-0000-0000-000000000000}{CAB54552-DEEA-4691-817E-ED4A4D1AFC72}][{AADCED64-746C-4633-A97C-D61349046527}{CAB54552-DEEA-4691-817E-ED4A4D1AFC72}]'

function Write-Step([string]$Message) { Write-Host "==> $Message" -ForegroundColor Cyan }
function Write-Plan([string]$Message) { Write-Host "    $Message" }
function Stop-Deploy([string]$Message) {
    Write-Host ''
    Write-Host "ERROR: $Message" -ForegroundColor Red
    exit 1
}

# UTF-8 avec marque d'ordre : Windows PowerShell 5 lit sinon un script en
# ANSI, et un tiret cadratin y devient un guillemet qui casse la syntaxe.
function Write-TextFile([string]$Path, [string]$Text, [bool]$Bom = $true) {
    [System.IO.File]::WriteAllText($Path, $Text, (New-Object System.Text.UTF8Encoding($Bom)))
}

function Read-B64([string]$Value) {
    return [System.Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($Value))
}

# Nom (sans domaine) d'un compte désigné par son SID : « Authenticated Users »
# s'appelle « Utilisateurs authentifiés » sur un contrôleur en français.
function Get-AccountName([string]$Sid) {
    $account = (New-Object System.Security.Principal.SecurityIdentifier($Sid)).Translate([System.Security.Principal.NTAccount]).Value
    return ($account -split '\\')[-1]
}

Write-Host ''
Write-Host "DumbMonit - Active Directory deployment for $Domain" -ForegroundColor White
Write-Host "Server: $Url   Token: $TokenHint...   Kit generated: $Generated UTC"
Write-Host ''

# ------------------------------------------------------------- prérequis

Write-Step 'Checking prerequisites'

$principal = New-Object System.Security.Principal.WindowsPrincipal([System.Security.Principal.WindowsIdentity]::GetCurrent())
if (-not $principal.IsInRole([System.Security.Principal.WindowsBuiltInRole]::Administrator)) {
    Stop-Deploy 'Run this script from a PowerShell console opened as administrator.'
}

foreach ($module in @('GroupPolicy', 'ActiveDirectory')) {
    if (-not (Get-Module -ListAvailable -Name $module)) {
        Stop-Deploy ("The $module PowerShell module is missing. On a server: " +
            "Install-WindowsFeature GPMC, RSAT-AD-PowerShell. On Windows 10/11: " +
            "Add-WindowsCapability -Online -Name Rsat.GroupPolicy.Management.Tools~~~~0.0.1.0 and " +
            "Rsat.ActiveDirectory.DS-LDS.Tools~~~~0.0.1.0.")
    }
    Import-Module $module -ErrorAction Stop -Verbose:$false
}

$ad = Get-ADDomain
if ($ad.DNSRoot.ToLowerInvariant() -ne $Domain) {
    Stop-Deploy "This kit was generated for the domain $Domain, but this machine is in $($ad.DNSRoot). Generate a kit for $($ad.DNSRoot) in DumbMonit."
}

# Administrateur du domaine (ou de l'entreprise) : créer une GPO et la lier
# en demande, et écrire dans SYSVOL aussi.
$groups = @([System.Security.Principal.WindowsIdentity]::GetCurrent().Groups | ForEach-Object { $_.Value })
$domainAdmins = "$($ad.DomainSID.Value)-512"
$isAdmin = ($groups -contains $domainAdmins) -or @($groups | Where-Object { $_ -like 'S-1-5-21-*-519' }).Count -gt 0
if (-not $isAdmin) {
    Stop-Deploy 'Run this script as a member of Domain Admins (or Enterprise Admins).'
}
Write-Plan "Domain $($ad.DNSRoot), running as $([System.Security.Principal.WindowsIdentity]::GetCurrent().Name)"

$sysvolRoot = "\\$($ad.DNSRoot)\SYSVOL\$($ad.DNSRoot)"
$kitDir = Join-Path $sysvolRoot 'DumbMonit'
$bootstrapPath = Join-Path $kitDir 'Install-DumbMonitAgent.ps1'

# -------------------------------------------------------------- retrait

if ($Remove) {
    Write-Step 'Removing the DumbMonit deployment'
    $gpo = Get-GPO -Name $GpoName -ErrorAction SilentlyContinue
    if ($gpo) {
        if ($PSCmdlet.ShouldProcess($GpoName, 'Delete the group policy and its links')) {
            Remove-GPO -Guid $gpo.Id -Confirm:$false
            Write-Plan "Group policy '$GpoName' deleted"
        }
    } else {
        Write-Plan "No group policy named '$GpoName'"
    }
    if (Test-Path -LiteralPath $kitDir) {
        if ($PSCmdlet.ShouldProcess($kitDir, 'Delete the installation kit')) {
            Remove-Item -LiteralPath $kitDir -Recurse -Force
            Write-Plan "Kit deleted from $kitDir"
        }
    }
    Write-Host ''
    Write-Host 'Done. Agents already installed keep running. To remove them, use -UninstallAgents before -Remove.'
    Write-Host 'Remember to stop new enrollments for this token in DumbMonit (Settings > Agents).'
    exit 0
}

# --------------------------------------------------------- cibles des liens

$links = New-Object System.Collections.Generic.List[string]
if ([string]::IsNullOrWhiteSpace($TargetOU)) {
    # L'OU des serveurs, s'il n'y en a qu'une : celle qui contient les
    # ordinateurs sous Windows Server, contrôleurs de domaine exclus.
    $dcOu = $ad.DomainControllersContainer
    $candidates = @(Get-ADComputer -Filter 'OperatingSystem -like "*Server*"' -Properties OperatingSystem |
        ForEach-Object { $_.DistinguishedName -replace '^CN=(\\,|[^,])+,', '' } |
        Where-Object { $_ -ne $dcOu -and $_ -like 'OU=*' } |
        Sort-Object -Unique)
    if ($candidates.Count -eq 1) {
        $TargetOU = $candidates[0]
        Write-Plan "Servers found in $TargetOU"
    } elseif ($candidates.Count -eq 0 -and -not $IncludeDomainControllers) {
        Stop-Deploy 'No organisational unit holding servers was found. Pass -TargetOU "OU=...,DC=..." (or -IncludeDomainControllers).'
    } elseif ($candidates.Count -gt 1) {
        Write-Host ''
        Write-Host 'Servers are spread over several organisational units:'
        $candidates | ForEach-Object { Write-Host "    $_" }
        Stop-Deploy 'Pick one with -TargetOU "OU=...,DC=..." (a parent OU covers its children), then run the script again.'
    }
}
if (-not [string]::IsNullOrWhiteSpace($TargetOU)) {
    $isDomainRoot = $TargetOU -eq $ad.DistinguishedName
    if (-not $isDomainRoot) {
        try { Get-ADOrganizationalUnit -Identity $TargetOU | Out-Null }
        catch { Stop-Deploy "Organisational unit not found: $TargetOU" }
    }
    $links.Add($TargetOU)
}
if ($IncludeDomainControllers) { $links.Add($ad.DomainControllersContainer) }

$groupSid = $null
if (-not [string]::IsNullOrWhiteSpace($SecurityGroup)) {
    try { $groupSid = (Get-ADGroup -Identity $SecurityGroup).SID.Value }
    catch { Stop-Deploy "Security group not found: $SecurityGroup" }
}

# --------------------------------------------------------------------- plan

Write-Step 'Plan'
Write-Plan "Group policy:  $GpoName (immediate scheduled task, SYSTEM, at every policy refresh)"
foreach ($link in $links) { Write-Plan "Linked to:     $link" }
if ($groupSid) { Write-Plan "Applies to:    members of $SecurityGroup only" }
else { Write-Plan 'Applies to:    every computer in the linked OUs' }
Write-Plan "Kit:           $kitDir"
if ($UseSysvol) { Write-Plan 'Agent binary:  copied to SYSVOL (servers without outbound access)' }
else { Write-Plan "Agent binary:  downloaded by each server from $Url" }
if ($UninstallAgents) { Write-Plan 'Mode:          UNINSTALL the agent from these servers' }
Write-Host ''

# ---------------------------------------------------------------- kit SYSVOL

Write-Step "Writing the installation kit to $kitDir"
if ($PSCmdlet.ShouldProcess($kitDir, 'Create the installation kit')) {
    if (-not (Test-Path -LiteralPath $kitDir)) { New-Item -ItemType Directory -Path $kitDir | Out-Null }

    # Le kit porte le jeton de flotte : SYSVOL est lisible par tout le domaine,
    # ce dossier ne l'est que par les ordinateurs visés et les administrateurs.
    $acl = New-Object System.Security.AccessControl.DirectorySecurity
    $acl.SetAccessRuleProtection($true, $false)
    $full = @('S-1-5-18', 'S-1-5-32-544', $domainAdmins)
    $readers = if ($groupSid) { @($groupSid) } else { @("$($ad.DomainSID.Value)-515") }
    # Les contrôleurs de domaine ne sont pas des « Domain Computers ».
    $readers += "$($ad.DomainSID.Value)-516"
    foreach ($sid in $full) {
        $acl.AddAccessRule((New-Object System.Security.AccessControl.FileSystemAccessRule(
            (New-Object System.Security.Principal.SecurityIdentifier($sid)), 'FullControl', 'ContainerInherit,ObjectInherit', 'None', 'Allow')))
    }
    foreach ($sid in $readers) {
        $acl.AddAccessRule((New-Object System.Security.AccessControl.FileSystemAccessRule(
            (New-Object System.Security.Principal.SecurityIdentifier($sid)), 'ReadAndExecute', 'ContainerInherit,ObjectInherit', 'None', 'Allow')))
    }
    Set-Acl -LiteralPath $kitDir -AclObject $acl

    Write-TextFile (Join-Path $kitDir 'install.ps1') (Read-B64 $InstallerB64)
    Write-TextFile $bootstrapPath (Read-B64 $BootstrapB64)

    $flag = Join-Path $kitDir 'uninstall.flag'
    if ($UninstallAgents) { Write-TextFile $flag 'Uninstall the DumbMonit agent.' $false }
    elseif (Test-Path -LiteralPath $flag) { Remove-Item -LiteralPath $flag -Force }

    $sysvolBinary = Join-Path $kitDir $BinaryName
    if ($UseSysvol) {
        if (-not $ExpectedSha256) { Stop-Deploy 'This DumbMonit server does not ship the Windows agent binary: -UseSysvol is not available.' }
        $download = Join-Path $env:TEMP "dumbmonit-$([guid]::NewGuid()).exe"
        Write-Plan "Downloading $Url/download/$BinaryName"
        $progress = $ProgressPreference
        $ProgressPreference = 'SilentlyContinue'
        try { Invoke-WebRequest -Uri "$Url/download/$BinaryName" -OutFile $download -UseBasicParsing }
        catch { Stop-Deploy "Download failed: $_" }
        finally { $ProgressPreference = $progress }
        $actual = (Get-FileHash -LiteralPath $download -Algorithm SHA256).Hash.ToLowerInvariant()
        if ($actual -ne $ExpectedSha256) {
            Remove-Item -LiteralPath $download -Force -ErrorAction SilentlyContinue
            Stop-Deploy "Checksum mismatch for the agent binary (expected $ExpectedSha256, got $actual). Nothing was copied. Download a new kit from DumbMonit."
        }
        Move-Item -LiteralPath $download -Destination $sysvolBinary -Force
        Write-Plan "Binary verified ($actual) and copied"
    } elseif (Test-Path -LiteralPath $sysvolBinary) {
        Remove-Item -LiteralPath $sysvolBinary -Force
    }
}

# ------------------------------------------------------- stratégie de groupe

Write-Step "Creating or updating the group policy '$GpoName'"
$gpo = Get-GPO -Name $GpoName -ErrorAction SilentlyContinue
if (-not $gpo) {
    if ($PSCmdlet.ShouldProcess($GpoName, 'Create the group policy')) {
        $gpo = New-GPO -Name $GpoName -Comment "Installs the DumbMonit agent ($Url). Managed by Deploy-DumbMonit.ps1."
        Write-Plan 'Group policy created'
    }
} else {
    Write-Plan 'Group policy already exists: updating it'
}

if ($gpo) {
    $gpoDir = Join-Path $sysvolRoot "Policies\{$($gpo.Id)}"
    $tasksDir = Join-Path $gpoDir 'Machine\Preferences\ScheduledTasks'
    $tasksPath = Join-Path $tasksDir 'ScheduledTasks.xml'
    $escape = { param($text) [System.Security.SecurityElement]::Escape($text) }
    $arguments = & $escape "-NoProfile -NonInteractive -ExecutionPolicy Bypass -File `"$bootstrapPath`""
    $description = & $escape "Installs or updates the DumbMonit agent ($Url). Managed by Deploy-DumbMonit.ps1."
    $changed = (Get-Date).ToUniversalTime().ToString('yyyy-MM-dd HH:mm:ss')
    # Élément ImmediateTaskV2 tel que la console de gestion des stratégies
    # l'écrit : la tâche est recréée et lancée à chaque rafraîchissement, et le
    # script décide seul s'il y a quelque chose à faire.
    $xml = @"
<?xml version="1.0" encoding="utf-8"?>
<ScheduledTasks clsid="{CC63F200-7309-4ba0-B154-A71CD118DBCC}">
  <ImmediateTaskV2 clsid="{9756B581-76EC-4169-9AFC-0CA8D43ADB5F}" name="$TaskName" image="0" changed="$changed" uid="{5A3E9C1D-2B7F-4D60-9E8A-D0B1C2A3F401}" userContext="0" removePolicy="0">
    <Properties action="R" name="$TaskName" runAs="NT AUTHORITY\System" logonType="S4U">
      <Task version="1.3">
        <RegistrationInfo>
          <Author>DumbMonit</Author>
          <Description>$description</Description>
        </RegistrationInfo>
        <Principals>
          <Principal id="Author">
            <UserId>NT AUTHORITY\System</UserId>
            <LogonType>S4U</LogonType>
            <RunLevel>HighestAvailable</RunLevel>
          </Principal>
        </Principals>
        <Settings>
          <IdleSettings>
            <Duration>PT5M</Duration>
            <WaitTimeout>PT1H</WaitTimeout>
            <StopOnIdleEnd>false</StopOnIdleEnd>
            <RestartOnIdle>false</RestartOnIdle>
          </IdleSettings>
          <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
          <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
          <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
          <AllowHardTerminate>true</AllowHardTerminate>
          <StartWhenAvailable>true</StartWhenAvailable>
          <AllowStartOnDemand>true</AllowStartOnDemand>
          <Enabled>true</Enabled>
          <Hidden>false</Hidden>
          <ExecutionTimeLimit>PT1H</ExecutionTimeLimit>
          <Priority>7</Priority>
          <DeleteExpiredTaskAfter>PT0S</DeleteExpiredTaskAfter>
        </Settings>
        <Triggers>
          <TimeTrigger>
            <StartBoundary>%LocalTimeXmlEx%</StartBoundary>
            <EndBoundary>%LocalTimeXmlEx%</EndBoundary>
            <Enabled>true</Enabled>
          </TimeTrigger>
        </Triggers>
        <Actions Context="Author">
          <Exec>
            <Command>powershell.exe</Command>
            <Arguments>$arguments</Arguments>
          </Exec>
        </Actions>
      </Task>
    </Properties>
  </ImmediateTaskV2>
</ScheduledTasks>
"@

    # Le fichier n'est réécrit, et la version de la GPO augmentée, que si la
    # tâche a changé (hors date) : relancer le script ne fait pas réappliquer
    # la stratégie pour rien.
    $previous = if (Test-Path -LiteralPath $tasksPath) { Get-Content -LiteralPath $tasksPath -Raw } else { '' }
    $strip = { param($text) $text -replace 'changed="[^"]*"', '' }
    if ((& $strip $previous).Trim() -ne (& $strip $xml).Trim()) {
        if ($PSCmdlet.ShouldProcess($GpoName, 'Write the scheduled task')) {
            if (-not (Test-Path -LiteralPath $tasksDir)) { New-Item -ItemType Directory -Path $tasksDir -Force | Out-Null }
            Write-TextFile $tasksPath $xml $false

            $adObject = Get-ADObject -Identity $gpo.Path -Properties versionNumber
            # Version sur 32 bits : partie utilisateur en haut, ordinateur en bas.
            $version = [int]$adObject.versionNumber
            $user = $version -shr 16
            $machine = ($version -band 0xFFFF) + 1
            $newVersion = ($user -shl 16) -bor $machine
            Set-ADObject -Identity $gpo.Path -Replace @{ gPCMachineExtensionNames = $ExtensionNames; versionNumber = $newVersion }
            $gptIni = Join-Path $gpoDir 'GPT.INI'
            Write-TextFile $gptIni "[General]`r`nVersion=$newVersion`r`n" $false
            Write-Plan "Scheduled task written (policy version $newVersion)"
        }
    } else {
        Write-Plan 'Scheduled task already up to date'
    }

    # -------------------------------------------------------------- filtrage

    $authenticatedUsers = Get-AccountName 'S-1-5-11'
    if ($groupSid) {
        if ($PSCmdlet.ShouldProcess($GpoName, "Apply only to members of $SecurityGroup")) {
            Set-GPPermission -Guid $gpo.Id -TargetName $SecurityGroup -TargetType Group -PermissionLevel GpoApply | Out-Null
            # Lecture conservée pour tous : sans elle, les ordinateurs ne
            # peuvent plus lire la GPO du tout (MS16-072).
            Set-GPPermission -Guid $gpo.Id -TargetName $authenticatedUsers -TargetType Group -PermissionLevel GpoRead -Replace | Out-Null
            Write-Plan "Security filtering: $SecurityGroup"
        }
    } elseif ($PSCmdlet.ShouldProcess($GpoName, 'Apply to every computer in the linked OUs')) {
        Set-GPPermission -Guid $gpo.Id -TargetName $authenticatedUsers -TargetType Group -PermissionLevel GpoApply -Replace | Out-Null
    }

    # ------------------------------------------------------------------ liens

    foreach ($link in $links) {
        $existing = @((Get-GPInheritance -Target $link).GpoLinks | Where-Object { $_.GpoId -eq $gpo.Id })
        if ($existing.Count -gt 0) {
            Write-Plan "Already linked to $link"
        } elseif ($PSCmdlet.ShouldProcess($link, "Link the group policy '$GpoName'")) {
            New-GPLink -Guid $gpo.Id -Target $link -LinkEnabled Yes | Out-Null
            Write-Plan "Linked to $link"
        }
    }
}

Write-Host ''
if ($WhatIfPreference) {
    Write-Host 'Nothing was changed (-WhatIf). Run the script again without -WhatIf to deploy.' -ForegroundColor Yellow
} else {
    Write-Host 'Done.' -ForegroundColor Green
    Write-Host 'Servers install the agent at their next policy refresh (within 90 minutes),'
    Write-Host 'or right away with: gpupdate /force   (on a server)'
    Write-Host 'Each server logs what it did in the Application event log, source "DumbMonit".'
    Write-Host 'Watch them arrive in DumbMonit, then delete this script: it holds the enrollment token.'
}
