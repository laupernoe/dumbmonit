<#
.SYNOPSIS
    Installs or updates the DumbMonit agent on this server. Run by the
    "DumbMonit Agent" group policy, as SYSTEM, at every policy refresh.

.DESCRIPTION
    Generated by DumbMonit (Settings > Agents > Deploy with Active Directory)
    and copied to SYSVOL by Deploy-DumbMonit.ps1. Do not edit: download a new
    kit and run Deploy-DumbMonit.ps1 again instead.

    - does nothing when the agent is already installed and up to date, or
      newer than this kit: the agent updates itself from the server, and the
      kit never downgrades it;
    - otherwise runs the DumbMonit installer (install.ps1, next to this file)
      with the install command generated by the server, plus this server's
      fully qualified name and organisational unit;
    - writes what it did to the Application event log (source "DumbMonit").
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

# Valeurs posées par le serveur DumbMonit à la génération du kit.
$Url            = '__DM_URL__'
$ExpectedSha256 = '__DM_SHA256__'
$KitVersion     = '__DM_VERSION__'
$Domain         = '__DM_DOMAIN__'
# Arguments de la commande d'installation telle que le serveur la génère
# (jeton de flotte, URL, empreintes…), en base64 : ils ne passent jamais par
# une ligne de commande visible ni par un journal.
$InstallArgsB64 = '__DM_INSTALL_ARGS_B64__'

$ServiceName = 'DumbMonitAgent'
$ExePath     = Join-Path $env:ProgramFiles 'DumbMonit\dumbmonit-agent.exe'
$ConfigPath  = Join-Path $env:ProgramData 'DumbMonit\agent.yaml'
$KitDir      = $PSScriptRoot
$Installer   = Join-Path $KitDir 'install.ps1'
$SysvolExe   = Join-Path $KitDir 'dumbmonit-agent-windows-x86_64.exe'
$UninstallFlag = Join-Path $KitDir 'uninstall.flag'
$EventSource = 'DumbMonit'

# Journal des événements Windows : c'est là qu'un administrateur regarde ce
# qu'une stratégie de groupe a fait sur un serveur. Une source absente est
# créée au premier passage ; un journal indisponible ne bloque rien.
function Write-Journal([int]$Id, [string]$Type, [string]$Message) {
    try {
        if (-not [System.Diagnostics.EventLog]::SourceExists($EventSource)) {
            New-EventLog -LogName Application -Source $EventSource
        }
        if ($Message.Length -gt 16000) { $Message = $Message.Substring($Message.Length - 16000) }
        Write-EventLog -LogName Application -Source $EventSource -EventId $Id -EntryType $Type -Message $Message
    } catch {
        Write-Output $Message
    }
}

# Le jeton ne doit jamais finir dans un journal, même si l'installateur
# échoue en recopiant sa ligne de commande.
function Hide-Secrets([string]$Text) {
    return ($Text -replace '(dmon|dmab|ezym)_[0-9A-Za-z]{6,}', '$1_********')
}

function Get-Sha256([string]$Path) {
    return (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash.ToLowerInvariant()
}

# « 0.14.2 », « 0.14.2-rc.1 » ou « dumbmonit-agent 0.14.2 » → [version] 0.14.2 ;
# $null si rien de lisible.
function ConvertTo-AgentVersion([string]$Text) {
    if ($Text -match '(\d+)\.(\d+)\.(\d+)') {
        return [version]"$($Matches[1]).$($Matches[2]).$($Matches[3])"
    }
    return $null
}

# Version de l'agent installé, d'après `dumbmonit-agent --version`.
function Get-AgentVersion([string]$Path) {
    try {
        $output = & $Path --version 2>$null | Select-Object -First 1
        return (ConvertTo-AgentVersion "$output")
    } catch {
        return $null
    }
}

# Lance l'installateur dans un processus à part : il se termine par `exit`, qui
# fermerait ce script avec lui. La commande passe en -EncodedCommand pour que
# ni les guillemets ni le jeton n'aient à survivre à une ligne de commande.
function Invoke-Installer([string]$Arguments) {
    $command = "& '$($Installer -replace "'", "''")' $Arguments"
    $encoded = [Convert]::ToBase64String([System.Text.Encoding]::Unicode.GetBytes($command))
    $powershell = Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe'
    $output = & $powershell -NoProfile -NonInteractive -ExecutionPolicy Bypass -EncodedCommand $encoded 2>&1 | Out-String
    return @{ Code = $LASTEXITCODE; Output = (Hide-Secrets $output) }
}

try {
    $installed = [bool](Get-Service -Name $ServiceName -ErrorAction SilentlyContinue) -and (Test-Path -LiteralPath $ExePath)

    # ------------------------------------------------------- retrait demandé
    if (Test-Path -LiteralPath $UninstallFlag) {
        if (-not $installed) { exit 0 }
        $result = Invoke-Installer '-Uninstall'
        if ($result.Code -eq 0) {
            Write-Journal 1004 Information "DumbMonit agent uninstalled by the group policy.`n`n$($result.Output)"
            exit 0
        }
        Write-Journal 1002 Error "DumbMonit agent uninstall failed (exit code $($result.Code)).`n`n$($result.Output)"
        exit 1
    }

    # --------------------------------------------------------- déjà à jour ?
    # À jour : le binaire de ce kit, ou un agent au moins aussi récent. La mise
    # à jour automatique remplace l'agent par celui du serveur dès que le
    # serveur est mis à jour : le kit, généré avant, ne doit pas le rétrograder
    # à chaque démarrage (puis le serveur le remettre à niveau, en boucle).
    $upToDate = $false
    if ($installed -and $ExpectedSha256 -and ((Get-Sha256 $ExePath) -eq $ExpectedSha256)) {
        $upToDate = $true
    } elseif ($installed) {
        $current = Get-AgentVersion $ExePath
        $kit = ConvertTo-AgentVersion $KitVersion
        if ($current -and $kit -and ($current -ge $kit)) { $upToDate = $true }
    }
    if ($upToDate) {
        $service = Get-Service -Name $ServiceName
        if ($service.Status -ne 'Running') {
            Start-Service -Name $ServiceName
            Write-Journal 1000 Information "DumbMonit agent is up to date; its service was stopped and has been started again."
        }
        exit 0
    }

    # ------------------------------------------------------ nom et rangement
    $computer = Get-CimInstance -ClassName Win32_ComputerSystem
    if (-not $computer.PartOfDomain) {
        Write-Journal 1003 Warning "This computer is not joined to a domain: the DumbMonit agent was not installed."
        exit 0
    }
    $fqdn = "$($env:COMPUTERNAME).$($computer.Domain)".ToLowerInvariant()

    # OU d'origine, telle que le client de stratégies de groupe l'a notée.
    $ou = $null
    try {
        $dn = (Get-ItemProperty -Path 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Group Policy\State\Machine' -Name 'Distinguished-Name').'Distinguished-Name'
        if ($dn) { $ou = ($dn -replace '^CN=(\\,|[^,])+,', '') }
    } catch { $ou = $null }

    # Une installation existante garde le nom sous lequel le serveur la connaît :
    # changer de nom créerait une seconde machine dans DumbMonit.
    $hostName = $fqdn
    if ($installed -and (Test-Path -LiteralPath $ConfigPath)) {
        $line = Select-String -LiteralPath $ConfigPath -Pattern '^hostname:\s*(.+)$' | Select-Object -First 1
        $hostName = if ($line) { $line.Matches[0].Groups[1].Value.Trim() } else { $null }
    }

    $arguments = [System.Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($InstallArgsB64))
    if ($hostName) { $arguments += " -HostName '$($hostName -replace "'", "''")'" }
    if ($ou) {
        # La valeur finit dans agent.yaml, écrit sans guillemets par l'installateur.
        $cleanOu = ($ou -replace '[:#\r\n]', ' ') -replace "'", "''"
        $arguments += " -Tags @{ ad_ou = '$cleanOu' }"
    }

    # ------------------------------------------ binaire partagé dans SYSVOL
    $localCopy = $null
    if (Test-Path -LiteralPath $SysvolExe) {
        # Copié en local avant d'être vérifié : ce qui est installé est
        # exactement ce qui a été vérifié.
        $localCopy = Join-Path $env:TEMP "dumbmonit-agent-$([guid]::NewGuid()).exe"
        Copy-Item -LiteralPath $SysvolExe -Destination $localCopy -Force
        $actual = Get-Sha256 $localCopy
        if (-not $ExpectedSha256 -or $actual -ne $ExpectedSha256) {
            Remove-Item -LiteralPath $localCopy -Force -ErrorAction SilentlyContinue
            Write-Journal 1002 Error "The DumbMonit agent binary in SYSVOL does not match the expected SHA-256 (expected '$ExpectedSha256', got '$actual'). Nothing was installed. Download a new kit from DumbMonit and run Deploy-DumbMonit.ps1 again."
            exit 1
        }
        $arguments += " -BinPath '$($localCopy -replace "'", "''")'"
    }

    # ---------------------------------------------------------- installation
    try {
        $result = Invoke-Installer $arguments
    } finally {
        if ($localCopy) { Remove-Item -LiteralPath $localCopy -Force -ErrorAction SilentlyContinue }
    }
    if ($result.Code -eq 0) {
        $verb = if ($installed) { 'updated' } else { 'installed' }
        $shown = if ($hostName) { $hostName } else { $env:COMPUTERNAME }
        Write-Journal 1001 Information "DumbMonit agent $verb as $shown for $Url (domain $Domain).`n`n$($result.Output)"
        exit 0
    }
    Write-Journal 1002 Error "DumbMonit agent installation failed (exit code $($result.Code)). If the checksum does not match, DumbMonit was upgraded since the kit was generated: download a new kit and run Deploy-DumbMonit.ps1 again.`n`n$($result.Output)"
    exit 1
} catch {
    Write-Journal 1002 Error (Hide-Secrets "DumbMonit agent deployment failed: $_")
    exit 1
}
