-- Secret de liaison remis mais pas encore présenté par l'agent.
--
-- Le secret part une seule fois, dans l'accusé de réception du lot qui lie la
-- machine. Si cette réponse se perd (coupure, délai dépassé), l'agent revient
-- sans secret et se voyait refuser pour toujours. Tant que l'agent n'a jamais
-- présenté le secret remis, et peu après sa remise, le serveur lui en remet un
-- autre au lieu de le refuser.
--
-- 1 par défaut : les machines déjà liées ont fait leurs preuves, et aucune ne
-- doit pouvoir être reprise par la seule mise à jour du serveur.
ALTER TABLE agent_hosts ADD COLUMN secret_confirmed INTEGER NOT NULL DEFAULT 1;
