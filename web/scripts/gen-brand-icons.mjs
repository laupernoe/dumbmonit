#!/usr/bin/env node
// Generates src/lib/brand-icons.ts from the `simple-icons` package (devDependency):
// only the handful of product marks the UI shows, as bare SVG paths, so the
// bundle never carries the whole set.
//   node scripts/gen-brand-icons.mjs
// Add a kind or a website platform below, run it again, commit the output.
import { writeFileSync, readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as si from 'simple-icons';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const version = JSON.parse(readFileSync(join(root, 'node_modules/simple-icons/package.json'), 'utf8')).version;

/**
 * Collector kind → simple-icons slug. Kinds without a mark keep their Lucide
 * icon; so do kinds whose mark is a wordmark unreadable at 16 px (VMware).
 */
const KINDS = {
	proxmox: 'proxmox',
	pbs: 'proxmox',
	pdm: 'proxmox',
	pmg: 'proxmox',
	synology: 'synology',
	opnsense: 'opnsense',
	truenas: 'truenas',
	victoriametrics: 'victoriametrics',
	victorialogs: 'victoriametrics',
	loki: 'grafana',
	graylog: 'graylog',
	nextcloud: 'nextcloud',
	immich: 'immich',
	paperless: 'paperlessngx',
	jellyfin: 'jellyfin',
	plex: 'plex',
	gitlab: 'gitlab',
	forgejo: 'forgejo',
	pihole: 'pihole',
	adguard: 'adguard',
	mikrotik: 'mikrotik',
	unifi: 'ubiquiti',
	homeassistant: 'homeassistant',
	redis: 'redis',
	mongodb: 'mongodb',
	rabbitmq: 'rabbitmq',
	traefik: 'traefikproxy',
	caddy: 'caddy',
	nginx: 'nginx',
	apache: 'apache',
	npm: 'nginxproxymanager',
	kubernetes: 'kubernetes',
	pfsense: 'pfsense',
	unraid: 'unraid',
	veeam: 'veeam',
	tailscale: 'tailscale',
	fortigate: 'fortinet',
	postgres: 'postgresql',
	mysql: 'mysql',
	mqtt: 'mqtt'
};

/** Website platform (crates/server/src/website/platform.rs `as_str`) → slug. */
const PLATFORMS = {
	wordpress: 'wordpress',
	shopify: 'shopify',
	wix: 'wix',
	squarespace: 'squarespace',
	webflow: 'webflow',
	ghost: 'ghost',
	drupal: 'drupal',
	joomla: 'joomla',
	prestashop: 'prestashop',
	nextjs: 'nextdotjs',
	nuxt: 'nuxt',
	gatsby: 'gatsby',
	hugo: 'hugo',
	jekyll: 'jekyll'
};

const bySlug = new Map(
	Object.values(si)
		.filter((i) => i && i.slug)
		.map((i) => [i.slug, i])
);
const used = [...new Set([...Object.values(KINDS), ...Object.values(PLATFORMS)])].sort();
const out = [
	'// Generated by scripts/gen-brand-icons.mjs — do not edit by hand.',
	`// Product marks from Simple Icons ${version} (https://simpleicons.org), CC0-1.0`,
	'// unless noted per icon below. Marks are trademarks of their owners and only',
	'// identify the product a monitor watches; no endorsement is implied.',
	'',
	'export interface BrandIcon {',
	'\t/** Product name, for a tooltip. */',
	'\ttitle: string;',
	'\t/** SVG path on a 24×24 viewBox. */',
	'\tpath: string;',
	'}',
	'',
	'const ICONS: Record<string, BrandIcon> = {'
];
for (const slug of used) {
	const icon = bySlug.get(slug);
	if (!icon) throw new Error(`simple-icons has no "${slug}"`);
	if (icon.license) out.push(`\t// ${icon.title}: ${icon.license.type} (${icon.license.url}), Simple Icons contributors`);
	out.push(`\t${JSON.stringify(slug)}: { title: ${JSON.stringify(icon.title)}, path: ${JSON.stringify(icon.path)} },`);
}
out.push('};', '');
for (const [name, obj] of [
	['KIND_SLUG', KINDS],
	['PLATFORM_SLUG', PLATFORMS]
]) {
	out.push(`const ${name}: Record<string, string> = {`);
	for (const [k, v] of Object.entries(obj)) out.push(`\t${JSON.stringify(k)}: ${JSON.stringify(v)},`);
	out.push('};', '');
}
out.push(
	'/** The product mark of a collector kind, if it has one. */',
	'export function kindBrand(kind: string): BrandIcon | null {',
	'\tconst slug = KIND_SLUG[kind];',
	'\treturn slug ? (ICONS[slug] ?? null) : null;',
	'}',
	'',
	'/** The mark of a website platform detected by the `website` kind, if it has one. */',
	'export function platformBrand(platform: string | null | undefined): BrandIcon | null {',
	'\tconst slug = platform ? PLATFORM_SLUG[platform] : undefined;',
	'\treturn slug ? (ICONS[slug] ?? null) : null;',
	'}',
	''
);
writeFileSync(join(root, 'src/lib/brand-icons.ts'), out.join('\n'));
console.log(`brand-icons.ts: ${used.length} icons from simple-icons ${version}`);
